import { useState } from "react"
import { generateChallenges } from "./challenges"
import { generateAIChallenges } from "./ai"

function Picker({ label, options, value, onChange }) {
  return (
    <div className="mb-5">
      <p className="font-semibold text-green-900 mb-2">{label}</p>
      <div className="flex flex-wrap gap-2">
        {options.map((opt) => (
          <button
            key={opt}
            onClick={() => onChange(opt)}
        c    className={`px-4 py-2 rounded-full border transition ${
              value === opt
                ? "bg-green-700 text-white border-green-700"
                : "bg-white text-green-800 border-green-300 hover:bg-green-50"
            }`}
          >
            {typeof opt === "number" ? `${opt} min` : opt}
          </button>
        ))}
      </div>
    </div>
  )
}

export default function App() {
  const [screen, setScreen] = useState("form")
  const [time, setTime] = useState(30)
  const [place, setPlace] = useState("Park")
  const [difficulty, setDifficulty] = useState("Easy")
  const [tasks, setTasks] = useState([])
  const [loadPct, setLoadPct] = useState(0)
  const [source, setSource] = useState("ai")

  const handleGenerate = async () => {
    const params = { time, place, difficulty }
    const fallback = generateChallenges(params)
    setScreen("loading")
    setLoadPct(0)
    try {
            const timeout = new Promise((_, reject) =>
        setTimeout(() => reject(new Error("AI timeout")), 300000)
      )
      const aiTasks = await Promise.race([
        generateAIChallenges(
          { ...params, count: fallback.length },
          (info) => {
            if (info.status === "progress") setLoadPct(Math.round(info.progress))
          }
        ),
        timeout,
      ])
    } catch (err) {
      console.error("AI failed, using templates:", err)
      setTasks(fallback)
      setSource("fallback")
    }
    setScreen("challenges")
  }

  const toggleTask = (id) =>
    setTasks((prev) => prev.map((t) => (t.id === id ? { ...t, done: !t.done } : t)))

  const doneCount = tasks.filter((t) => t.done).length
  const allDone = tasks.length > 0 && doneCount === tasks.length

  return (
    <div className="min-h-screen bg-green-100 flex items-center justify-center p-4">
      <div className="bg-white/80 rounded-2xl shadow-lg p-6 w-full max-w-md">
        <h1 className="text-3xl font-bold text-green-800 mb-1">🚶 Walking Challenge AI</h1>
        <p className="text-green-700 mb-6 text-sm">Phone se nikal, duniya dekh. 🌱</p>

        {screen === "form" && (
          <>
            <Picker label="⏱️ Walking time" options={[10, 20, 30, 60]} value={time} onChange={setTime} />
            <Picker label="📍 Place" options={["Park", "City", "College", "Neighborhood"]} value={place} onChange={setPlace} />
            <Picker label="🔥 Difficulty" options={["Easy", "Medium", "Hard"]} value={difficulty} onChange={setDifficulty} />
            <button
              onClick={handleGenerate}
              className="w-full bg-green-700 hover:bg-green-800 text-white font-bold py-3 rounded-xl mt-2"
            >
              Get Your Outdoor Challenge
            </button>
          </>
        )}

        {screen === "loading" && (
          <div className="text-center py-8">
            <p className="text-5xl mb-3 animate-bounce">🤖</p>
            <p className="font-semibold text-green-900">
              {loadPct > 0 && loadPct < 100
                ? `AI model load ho raha hai... ${loadPct}%`
                : "AI tumhare liye challenges soch raha hai..."}
            </p>
            <p className="text-sm text-green-700 mt-2">
              Pehli baar ~500MB download hoga. Uske baad cache se turant chalega.
            </p>
          </div>
        )}

        {screen === "challenges" && (
          <>
            <h2 className="text-xl font-bold text-green-900 mb-1">
              {time}-Minute {place} Challenge
            </h2>
            <p className="text-xs text-green-700 mb-3">
              {source === "ai" ? "🤖 Generated by open-source AI (running in your browser)" : "📋 Offline template mode"}
            </p>
            <ul className="space-y-2 mb-4">
              {tasks.map((t) => (
                <li key={t.id}>
                  <button
                    onClick={() => toggleTask(t.id)}
                    className={`w-full text-left p-3 rounded-xl border transition ${
                      t.done
                        ? "bg-green-200 border-green-400 line-through text-green-700"
                        : "bg-white border-green-200 hover:bg-green-50"
                    }`}
                  >
                    {t.done ? "✅ " : "⬜ "}
                    {t.text}
                  </button>
                </li>
              ))}
            </ul>
            <p className="text-sm text-green-800 mb-3">
              {doneCount} / {tasks.length} complete
            </p>
            <button
              onClick={() => setScreen(allDone ? "done" : "form")}
              className="w-full bg-green-700 hover:bg-green-800 text-white font-bold py-3 rounded-xl"
            >
              {allDone ? "Finish Walk 🎉" : "← Back"}
            </button>
          </>
        )}

        {screen === "done" && (
          <div className="text-center">
            <p className="text-6xl mb-3">🎉</p>
            <h2 className="text-2xl font-bold text-green-900 mb-2">Walk Complete!</h2>
            <p className="text-green-700 mb-5">
              Tune {tasks.length} challenges poore kiye. Screen se bahar aane ke liye shabaash!
            </p>
            <button
              onClick={() => setScreen("form")}
              className="w-full bg-green-700 hover:bg-green-800 text-white font-bold py-3 rounded-xl"
            >
              New Walk
            </button>
          </div>
        )}
      </div>
    </div>
  )
}